router.patch('/kitchen/ingredients/:ingredientId', ...kitchenAccess, kitchen.updateIngredient);
router.get('/kitchen/recipe', ...kitchenAccess, kitchen.getRecipe);
router.put('/kitchen/recipe', ...kitchenAccess, kitchen.updateRecipe);
router.get('/kitchen/recipes', ...kitchenAccess, kitchen.listRecipes);
router.post('/kitchen/recipes', ...kitchenAccess, kitchen.createRecipe);
router.put('/kitchen/recipes/:recipeId', ...kitchenAccess, kitchen.updateRecipeById);
router.delete('/kitchen/recipes/:recipeId', ...kitchenAccess, kitchen.deleteRecipe);
router.post('/kitchen/recipes/:recipeId/activate', ...kitchenAccess, kitchen.activateRecipe);
router.get('/kitchen/batches', ...batchAccess, kitchen.listBatches);
router.get('/kitchen/movements', ...kitchenAccess, kitchen.listInventoryMovements);
router.get('/kitchen/purchase-orders', ...kitchenAccess, kitchen.listPurchaseOrders);
