router.get('/owner/assets', ...ownerOnly, owner.listAssets);
router.post('/owner/assets', ...ownerOnly, owner.createAsset);
router.patch('/owner/assets/:assetId', ...ownerOnly, owner.updateAsset);
router.post('/owner/assets/:assetId/approve-writeoff', ...ownerOnly, owner.approveAssetWriteoff);
router.get('/owner/users', ...ownerOnly, owner.listUsers);
